/** Convenience lookup. */
const index = new Map<string, CardDef>()
for (const c of ALL_CARDS) index.set(c.id, c)

export function getCard(id: string): CardDef {
  const c = index.get(id)
  if (!c) throw new Error(`Card not found: ${id}`)
  return c
}

export function getSuperstar(id: string): SuperstarDef {
  const s = SUPERSTARS.find((x) => x.id === id)
  if (!s) throw new Error(`Superstar not found: ${id}`)
  return s
}
